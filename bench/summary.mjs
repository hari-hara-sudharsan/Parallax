// Aggregates every results/<chain>-*.json run into results/SUMMARY.md.   node summary.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const EXPLORER = {
  1301: (h) => `https://sepolia.uniscan.xyz/tx/${h}`,
  84532: (h) => `https://sepolia.basescan.org/tx/${h}`,
};
const LASNA = (h) => `https://lasna.reactscan.net/tx/${h}`;
const short = (h) => (h ? `${h.slice(0, 8)}…${h.slice(-4)}` : "—");

function pct(xs, p) {
  if (!xs.length) return undefined;
  const s = [...xs].sort((a, b) => a - b);
  const i = Math.min(s.length - 1, Math.max(0, Math.ceil((p / 100) * s.length) - 1));
  return s[i];
}

export function writeSummary(dir) {
  const rows = readdirSync(dir)
    .filter((f) => /^(unichain|base)-.*\.json$/.test(f))
    .flatMap((f) => JSON.parse(readFileSync(join(dir, f), "utf8")).map((r) => ({ ...r, file: f })));

  const lines = [
    "# Parallax: live benchmark results",
    "",
    "Generated by `bench/bench.mjs` (`CHAIN=base|unichain ./tw.sh bench N`). Every round is a real testnet loop:",
    "**origin swap → reactive tx on Lasna → callback execution**. Nothing off-chain triggers the callback.",
    "",
    "- **Blocks** = `executedBlock − originBlock`, both from the executor's on-chain `Execution` record (exact).",
    "- **Seconds (timestamps)** = `executedAt − origin block timestamp` (1 s resolution).",
    "- **Seconds (blocks)** = blocks × the chain's nominal block time (Base 200 ms, Unichain 1 s).",
    "- **Wall-clock** is measured by polling public RPCs from our machine, so it is an upper bound.",
    "- Failures are kept, with their reason.",
    "",
    "## Summary",
    "",
    "| Chain | Rounds | Filled | Blocks p50 / p90 / min / max | Seconds by blocks p50 / p90 | Seconds by timestamp p50 / p90 | Wall-clock p50 |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const chain of ["base", "unichain"]) {
    const rs = rows.filter((r) => r.chain === chain);
    if (!rs.length) continue;
    const ok = rs.filter((r) => r.ok);
    const b = ok.map((r) => r.latencyBlocks);
    const sb = ok.map((r) => r.latencySecondsByBlocks);
    const st = ok.map((r) => r.latencySecondsByTimestamp);
    const w = ok.map((r) => r.wallClockMs / 1000);
    const f = (x, d = 1) => (x === undefined ? "–" : Number(x).toFixed(d));
    lines.push(
      `| ${chain === "base" ? "Base Sepolia" : "Unichain Sepolia"} | ${rs.length} | ${ok.length}/${rs.length} | ` +
        `${pct(b, 50) ?? "–"} / ${pct(b, 90) ?? "–"} / ${b.length ? Math.min(...b) : "–"} / ${b.length ? Math.max(...b) : "–"} | ` +
        `${f(pct(sb, 50))} s / ${f(pct(sb, 90))} s | ${f(pct(st, 50), 0)} s / ${f(pct(st, 90), 0)} s | ${f(pct(w, 50))} s |`,
    );
  }

  for (const chain of ["base", "unichain"]) {
    const rs = rows.filter((r) => r.chain === chain);
    if (!rs.length) continue;
    const tx = EXPLORER[rs[0].chainId];
    lines.push(
      "",
      `## ${chain === "base" ? "Base Sepolia" : "Unichain Sepolia"}: every round`,
      "",
      "| # | Rule | Origin swap | Reactive (Lasna) | Callback | Blocks | s (ts) | Wall | Result |",
      "|---|---|---|---|---|---|---|---|---|",
    );
    rs.forEach((r, i) =>
      lines.push(
        `| ${i + 1} | ${r.kind}${r.ruleId ? ` #${r.ruleId}` : ""} | ${r.originTx ? `[${short(r.originTx)}](${tx(r.originTx)})` : "—"} | ` +
          `${r.reactiveTx ? `[${short(r.reactiveTx)}](${LASNA(r.reactiveTx)})` : "—"} | ` +
          `${r.callbackTx ? `[${short(r.callbackTx)}](${tx(r.callbackTx)})` : "—"} | ${r.latencyBlocks ?? "—"} | ` +
          `${r.latencySecondsByTimestamp ?? "—"} | ${r.wallClockMs ? (r.wallClockMs / 1000).toFixed(1) + " s" : "—"} | ${r.ok ? "✅ filled" : `❌ ${r.error}`} |`,
      ),
    );
  }
  // ── Keeper-bot baseline (bench/keeper.mjs): same pool, same crossing swap, an off-chain bot fills instead.
  const keeper = readdirSync(dir)
    .filter((f) => /^keeper-(unichain|base)-.*\.json$/.test(f))
    .flatMap((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
  if (keeper.length) {
    lines.push(
      "",
      "## Parallax vs a keeper bot (same pool, same crossing swap)",
      "",
      "`bench/keeper.mjs` runs a classic off-chain bot: it polls the pool every 250 ms over the public RPC and sends its",
      "own market sell when the stop is crossed. This is a *good* bot (fast polling, warm connection, funded hot key);",
      "real keepers also carry downtime, gas-spike and skipped-order risk that this benchmark does not model.",
      "",
      "| Chain | Executor | Rounds | Filled | Blocks p50 / p90 / min / max | Seconds by blocks p50 |",
      "|---|---|---|---|---|---|",
    );
    for (const chain of ["base", "unichain"]) {
      const ms = chain === "base" ? 200 : 1000;
      const groups = [
        ["Parallax (on-chain, no bot)", rows.filter((r) => r.chain === chain)],
        ["Keeper bot (off-chain)", keeper.filter((r) => r.chain === chain)],
      ];
      for (const [label, rs] of groups) {
        if (!rs.length) continue;
        const b = rs.filter((r) => r.ok).map((r) => r.latencyBlocks);
        lines.push(
          `| ${chain === "base" ? "Base Sepolia" : "Unichain Sepolia"} | ${label} | ${rs.length} | ${b.length}/${rs.length} | ` +
            `${pct(b, 50) ?? "–"} / ${pct(b, 90) ?? "–"} / ${b.length ? Math.min(...b) : "–"} / ${b.length ? Math.max(...b) : "–"} | ` +
            `${b.length ? ((pct(b, 50) * ms) / 1000).toFixed(1) + " s" : "–"} |`,
        );
      }
    }
  }

  writeFileSync(join(dir, "SUMMARY.md"), lines.join("\n") + "\n");
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("summary.mjs")) {
  writeSummary(join(dirname(fileURLToPath(import.meta.url)), "..", "results"));
  console.log("wrote results/SUMMARY.md");
}
