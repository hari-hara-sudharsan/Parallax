#!/usr/bin/env python3
"""What one second of latency costs a stop-loss, measured on real crash data.

Downloads Binance's public ETH/USDT 1-second candles for 10 Oct 2025, checks them against the SHA-256 that Binance
publishes, and finds the worst 30 minutes of that day. For every second in that window we ask: if a stop triggered
at this second and only filled L seconds later, how far had the price moved against the seller?

    cost(t, L) = (P(t) - P(t + L)) / P(t)          in basis points, P = 1-second close, linearly interpolated

Two populations are reported:
  * every second in the window, and
  * "stop seconds": seconds whose close is the lowest of the trailing 60 s, i.e. when stops are actually being hit.

Latencies compared (seconds, all from our own measurements unless marked derived):
  1.4  Parallax median (7 Base blocks, results/SUMMARY.md)
  2.0  Parallax p90 and the 250 ms keeper bot's median (10 blocks)
  4.4  legacy Reactive, derived: our loop + 3 s average extra wait for a ~7 s reactive block
  7.4  legacy Reactive, derived worst case: our loop + 6 s

Standard library only. Run: python analysis/what_a_second_buys.py   (writes results/what-a-second-buys.md)
"""

from __future__ import annotations

import csv
import math
import hashlib
import io
import statistics
import sys
import urllib.request
import zipfile
from datetime import datetime, timezone
from pathlib import Path

DAY = "2025-10-10"
URL = f"https://data.binance.vision/data/spot/daily/klines/ETHUSDT/1s/ETHUSDT-1s-{DAY}.zip"
WINDOW_S = 30 * 60
STOP_LOOKBACK_S = 60
LATENCIES = [
    (1.4, "Parallax, median"),
    (2.0, "Parallax p90 / keeper bot median"),
    (4.4, "Legacy Reactive, derived average"),
    (7.4, "Legacy Reactive, derived worst"),
]
POSITION_USD = 100_000

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "analysis" / "data"
OUT = ROOT / "results" / "what-a-second-buys.md"


def fetch(url: str, dest: Path) -> None:
    if dest.exists():
        return
    req = urllib.request.Request(url, headers={"User-Agent": "parallax-analysis"})
    with urllib.request.urlopen(req, timeout=60) as r:
        dest.write_bytes(r.read())


def load_closes() -> tuple[list[float], list[float], str]:
    DATA.mkdir(parents=True, exist_ok=True)
    zpath = DATA / URL.rsplit("/", 1)[1]
    cpath = zpath.with_suffix(".zip.CHECKSUM")
    fetch(URL, zpath)
    fetch(URL + ".CHECKSUM", cpath)
    expected = cpath.read_text().split()[0].lower()
    actual = hashlib.sha256(zpath.read_bytes()).hexdigest()
    if actual != expected:
        sys.exit(f"SHA-256 mismatch: got {actual}, Binance publishes {expected}")
    with zipfile.ZipFile(zpath) as z:
        rows = list(csv.reader(io.TextIOWrapper(z.open(z.namelist()[0]))))
    unit = 1e6 if int(rows[0][0]) > 10**14 else 1e3  # Binance switched open times to microseconds in 2025
    ts = [int(r[0]) / unit for r in rows]
    closes = [float(r[4]) for r in rows]
    return ts, closes, actual


def worst_window(closes: list[float]) -> int:
    best, start = 0.0, 0
    for i in range(0, len(closes) - WINDOW_S, 10):
        w = closes[i : i + WINDOW_S]
        drop = (w[0] - min(w)) / w[0]
        if drop > best:
            best, start = drop, i
    return start


def price_at(closes: list[float], t: float) -> float:
    i = int(t)
    frac = t - i
    return closes[i] if frac == 0 else closes[i] * (1 - frac) + closes[i + 1] * frac


def nearest_rank(xs: list[float], q: float) -> float:
    s = sorted(xs)
    k = max(1, math.ceil(q * len(s)))  # nearest-rank: the smallest value with at least q of the data at or below it
    return s[k - 1]


def main() -> None:
    ts, closes, sha = load_closes()
    s0 = worst_window(closes)
    end = s0 + WINDOW_S
    start_txt = datetime.fromtimestamp(ts[s0], timezone.utc).strftime("%H:%M:%S")
    end_txt = datetime.fromtimestamp(ts[end], timezone.utc).strftime("%H:%M:%S")
    lo = min(closes[s0:end])
    drop_pct = (closes[s0] - lo) / closes[s0] * 100

    seconds = range(s0, end)
    stop_seconds = [t for t in seconds if closes[t] <= min(closes[max(0, t - STOP_LOOKBACK_S) : t + 1])]

    def costs(pop, lat):
        return [(closes[t] - price_at(closes, t + lat)) / closes[t] * 10_000 for t in pop]

    lines = [
        "# What a second buys: stop-loss latency on real crash data",
        "",
        "Generated by [`analysis/what_a_second_buys.py`](../analysis/what_a_second_buys.py). Data: Binance ETH/USDT "
        f"1-second candles for {DAY} ([source]({URL})), SHA-256 `{sha}` checked against Binance's published checksum.",
        "",
        f"**Window:** the worst 30 minutes of the day, {start_txt}–{end_txt} UTC. ETH fell **{drop_pct:.1f}%** "
        f"({closes[s0]:,.2f} → {lo:,.2f}).",
        "",
        "For every second *t* in the window: if a stop triggered at *t* and filled *L* seconds later, how far had the "
        "price fallen? `cost = (P(t) − P(t+L)) / P(t)`, in basis points (1 bp = $10 on a $100k position). Negative "
        "means the price had bounced. Percentiles are nearest-rank, so every value is one that occurred.",
        "",
    ]
    for title, pop in [
        (f"Every second in the window (n = {len(seconds)})", list(seconds)),
        (f"Stop seconds: the close is the lowest of the last {STOP_LOOKBACK_S} s (n = {len(stop_seconds)})", stop_seconds),
    ]:
        lines += [f"## {title}", "", "| Fill latency | Median | Mean | p95 | $ lost per $100k (mean) |", "|---|---|---|---|---|"]
        for lat, label in LATENCIES:
            c = costs(pop, lat)
            mean = statistics.fmean(c)
            lines.append(
                f"| **{lat:.1f} s**: {label} | {statistics.median(c):.1f} bps | {mean:.1f} bps | "
                f"{nearest_rank(c, 0.95):.1f} bps | ${mean * POSITION_USD / 10_000:,.0f} |"
            )
        base, base95 = statistics.fmean(costs(pop, 1.4)), nearest_rank(costs(pop, 1.4), 0.95)
        lines += ["", "| Parallax (1.4 s) vs | Kept on average | Kept at the p95 (p95 vs p95) |", "|---|---|---|"]
        for lat, label in LATENCIES[1:]:
            extra = statistics.fmean(costs(pop, lat)) - base
            tail = nearest_rank(costs(pop, lat), 0.95) - base95
            lines.append(f"| {label} ({lat:.1f} s) | {extra:.1f} bps (${extra * POSITION_USD / 10_000:,.0f} per $100k) "
                         f"| **{tail:.1f} bps (${tail * POSITION_USD / 10_000:,.0f} per $100k)** |")
        lines.append("")
    lines += [
        "## How to read this",
        "",
        "- **The tail is the point.** On an average second, fall and bounce largely cancel, so averages are small. A stop "
        "exists for the bad seconds: the p95 column is what a slow fill costs exactly when protection matters.",
        "- The cost is signed (a bounce counts in your favour), which makes these numbers conservative compared with "
        "measuring the largest move inside the wait.",
        "- These are exchange price moves, not our Uniswap v4 pool. They measure how far the market runs while a stop "
        "waits to fill; a thin pool would gap further.",
        "- 1.4 s and 2.0 s are measured (`results/SUMMARY.md`, keeper baseline). 4.4 s and 7.4 s are **derived**: our "
        "measured loop with Lasna's ~1 s block replaced by a ~7 s legacy block (on average a transaction waits half a "
        "block, so +3 s; at worst a full block, +6 s). Nothing was run on legacy Reactive.",
        "- Prices between 1-second closes are linearly interpolated.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
